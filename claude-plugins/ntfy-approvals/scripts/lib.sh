#!/usr/bin/env bash
# ntfy-approvals — shared helpers for the hook scripts.
# Deliberately jq-free: works on a bare remote server with bash + curl only.

NA_NAME="ntfy-approvals"
NA_VERSION="0.1.0"

# ---------------------------------------------------------------------------
# state
# ---------------------------------------------------------------------------
na_state_dir() {
  printf '%s' "${NTFY_APPROVALS_STATE_DIR:-$HOME/.claude}"
}

na_config_file() {
  printf '%s/ntfy-approvals.env' "$(na_state_dir)"
}

na_control_dir() {
  printf '%s/control' "$(na_state_dir)"
}

# na_log <text> — only when NTFY_APPROVALS_DEBUG=1
na_log() {
  [ "${NTFY_APPROVALS_DEBUG:-0}" = "1" ] || return 0
  printf '%s\t%s\n' "$(date '+%F %T')" "$*" \
    >>"$(na_state_dir)/ntfy-approvals.log" 2>/dev/null || true
}

# ---------------------------------------------------------------------------
# tiny JSON helpers (hook payloads are single-line JSON)
# ---------------------------------------------------------------------------

# jget <json> <key> -> first string value of "key"
jget() {
  printf '%s' "$1" \
    | tr -d '\r\n' \
    | sed -n 's/.*"'"$2"'"[[:space:]]*:[[:space:]]*"\([^"\\]*\)".*/\1/p' \
    | head -n 1
}

# json_escape <text> -> safe to embed inside a JSON string
json_escape() {
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

# na_sanitize <text> -> strips bytes that break JSON / OSC payloads, caps length
na_sanitize() {
  local s
  s=$(printf '%s' "$1" | LC_ALL=C tr -d '[:cntrl:]"\\')
  printf '%s' "${s:0:160}"
}

# na_project <cwd> -> last path segment, / and \ aware
na_project() {
  local name
  name=$(printf '%s' "$1" | sed 's#/*$##; s#.*[\\/]##')
  printf '%s' "${name:-claude}"
}

# ---------------------------------------------------------------------------
# topics
# ---------------------------------------------------------------------------
na_rand_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1" 2>/dev/null && return 0
  fi
  od -An -tx1 -N "$1" /dev/urandom 2>/dev/null | tr -d ' \n'
}

na_topic_slug() {
  local prefix=$1 host rand
  host=$(hostname 2>/dev/null | tr 'A-Z' 'a-z' | tr -cd 'a-z0-9' | cut -c1-12)
  [ -n "$host" ] || host="host"
  rand=$(na_rand_hex 8)
  [ -n "$rand" ] || rand=$(date +%s | cut -c1-10)
  printf '%s-%s-%s' "$prefix" "$host" "$rand"
}

na_valid_topic() {
  case "$1" in
    ''|*[!A-Za-z0-9_-]*) return 1 ;;
    *) [ "${#1}" -le 64 ] ;;
  esac
}

# na_load_config — sets NOTIFY_TOPIC / CONTROL_TOPIC / NTFY_BASE / NTFY_TOKEN.
# Generates and persists a random topic pair on first use.
na_load_config() {
  local dir file
  dir=$(na_state_dir)
  file=$(na_config_file)
  mkdir -p "$dir" 2>/dev/null || true
  chmod 700 "$dir" 2>/dev/null || true

  if [ -f "$file" ]; then
    [ -n "${NOTIFY_TOPIC:-}" ]  || NOTIFY_TOPIC=$(sed -n 's/^NOTIFY_TOPIC=//p' "$file" | head -n 1)
    [ -n "${CONTROL_TOPIC:-}" ] || CONTROL_TOPIC=$(sed -n 's/^CONTROL_TOPIC=//p' "$file" | head -n 1)
  fi

  if ! na_valid_topic "${NOTIFY_TOPIC:-}" || ! na_valid_topic "${CONTROL_TOPIC:-}"; then
    NOTIFY_TOPIC=$(na_topic_slug claude)
    CONTROL_TOPIC=$(na_topic_slug claude-ctl)
    ( umask 077
      printf '# generated by %s %s — treat these as passwords\nNOTIFY_TOPIC=%s\nCONTROL_TOPIC=%s\n' \
        "$NA_NAME" "$NA_VERSION" "$NOTIFY_TOPIC" "$CONTROL_TOPIC" >"$file" )
    chmod 600 "$file" 2>/dev/null || true
    na_log "generated topics in $file"
  fi

  NTFY_BASE=${NTFY_APPROVALS_BASE:-https://ntfy.sh}
  NTFY_BASE=${NTFY_BASE%/}
  NTFY_TOKEN=${NTFY_APPROVALS_TOKEN:-}
  export NOTIFY_TOPIC CONTROL_TOPIC NTFY_BASE NTFY_TOKEN
}

# ---------------------------------------------------------------------------
# ntfy
# ---------------------------------------------------------------------------

# na_publish <topic> <message> [actions-json] [priority]
na_publish() {
  local topic=$1 msg=$2 actions=${3:-} prio=${4:-3}
  local payload hdr=()
  command -v curl >/dev/null 2>&1 || return 1
  if [ -n "${NTFY_TOKEN:-}" ]; then
    hdr=(-H "Authorization: Bearer $NTFY_TOKEN")
  fi
  if [ -n "$actions" ]; then
    payload=$(printf '{"topic":"%s","title":"Claude Code","message":"%s","priority":%s,"tags":["bell"],"actions":%s}' \
      "$topic" "$(json_escape "$msg")" "$prio" "$actions")
  else
    payload=$(printf '{"topic":"%s","title":"Claude Code","message":"%s","priority":%s,"tags":["bell"]}' \
      "$topic" "$(json_escape "$msg")" "$prio")
  fi
  curl -fsS -m 8 -H "Content-Type: application/json" ${hdr[@]+"${hdr[@]}"} \
    -d "$payload" "$NTFY_BASE/" >/dev/null 2>&1
}

# ---------------------------------------------------------------------------
# terminal
# ---------------------------------------------------------------------------

# na_seq_json <title> <already-sanitized body> -> JSON-escaped escape sequence
# (no surrounding quotes, so callers can emit ONE object per hook run)
na_seq_json() {
  printf '\\u0007\\u001b]0;%s\\u0007\\u001b]9;%s\\u0007\\u001b]777;notify;%s;%s\\u0007\\u001b]99;i=claude:d=1;%s\\u0007' \
    "$1: $2" "$2" "$1" "$2" "$1: $2"
}

# na_frame <title> <body> [extra json fields] -> one complete hook JSON object
na_frame() {
  printf '{"terminalSequence":"%s"%s}\n' "$(na_seq_json "$1" "$2")" "${3:-}"
}

# na_tmux_hint <text> — status-line fallback when the terminal drops OSC
na_tmux_hint() {
  [ -n "${TMUX:-}" ] || return 0
  command -v tmux >/dev/null 2>&1 || return 0
  tmux display-message -d 8000 "$1" >/dev/null 2>&1 || true
}
