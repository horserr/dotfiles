USAGE = f"""{NAME} {VERSION}

usage: {NAME}.py <command>

  notify              hook entry point (Notification / Stop / StopFailure)
  approve             hook entry point (PermissionRequest)
  control topic       print topics and the phone link (with a QR code)
  control listen      run the relay daemon
  control send TXT    publish TXT to the control topic
  control status      print state, topics and relay status
  control init        generate the topic pair if missing
"""


def main(argv: list[str]) -> int:
    # Windows consoles default to a legacy code page; the QR uses U+2580.
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
    except (AttributeError, ValueError, OSError):
        pass

    if len(argv) < 2 or argv[1] in ("-h", "--help", "help"):
        print(USAGE)
        return 0
    if argv[1] in ("-v", "--version"):
        print(f"{NAME} {VERSION}")
        return 0

    command = argv[1]
    rest = argv[2:]

    if command == "notify":
        return cmd_notify()
    if command == "approve":
        return cmd_approve()
    if command == "_publish":
        return cmd_publish_child(rest)
    if command == "control":
        if not rest:
            print(USAGE)
            return 0
        action = rest[0]
        if action == "topic":
            return cmd_topic()
        if action == "listen":
            return cmd_listen()
        if action == "send":
            return cmd_send(rest[1:])
        if action == "status":
            return cmd_status()
        if action == "init":
            cmd_topic()
            return 0
        print(USAGE)
        return 2

    print(USAGE)
    return 2


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv))
    except KeyboardInterrupt:
        sys.exit(0)
