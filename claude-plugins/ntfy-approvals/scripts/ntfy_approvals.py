#!/usr/bin/env python3
"""ntfy-approvals — Claude Code notifications and phone approvals over ntfy.

Subcommands
-----------
notify            hook entry point for Notification / Stop / StopFailure
approve           hook entry point for PermissionRequest (publishes Allow/Deny
                  buttons, waits for the relay, answers the hook)
control topic     print topics + phone subscription link (QR if qrencode)
control listen    relay: control topic -> decision files / tmux input
control send TXT  publish TXT to the control topic
control status    show state, topics, relay status
control init      create the random topic pair now

Only the standard library is used, so it runs on a bare remote server with
`python3` and nothing else.
"""

from __future__ import annotations

import http.client
import json
import os
import re
import secrets
import socket
import ssl
import subprocess
import sys
import time
from contextlib import contextmanager
from pathlib import Path
from urllib.parse import urlsplit

_HERE = Path(__file__).resolve().parent
if str(_HERE) not in sys.path:
    sys.path.insert(0, str(_HERE))

import qrgen

NAME = "ntfy-approvals"
VERSION = "0.3.0"

TOPIC_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
REQ_RE = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
DEFAULT_BASE = "https://ntfy.sh"

# ---------------------------------------------------------------------------
# environment / state
# ---------------------------------------------------------------------------


def env(name: str, default: str = "") -> str:
    return os.environ.get(name) or default


def flag(name: str, default: bool) -> bool:
    value = os.environ.get(name)
    if value is None or value == "":
        return default
    return value.strip().lower() not in ("0", "false", "no", "off")


def number(name: str, default: int) -> int:
    try:
        return int(os.environ.get(name, "").strip())
    except ValueError:
        return default


def state_dir() -> Path:
    override = env("NTFY_APPROVALS_STATE_DIR")
    return Path(override) if override else Path.home() / ".claude"


def config_path() -> Path:
    return state_dir() / "ntfy-approvals.env"


def control_dir() -> Path:
    return state_dir() / "control"


def log_path() -> Path:
    return state_dir() / "ntfy-approvals.log"


def log(message: str) -> None:
    if not flag("NTFY_APPROVALS_DEBUG", False):
        return
    try:
        log_path().parent.mkdir(parents=True, exist_ok=True)
        with log_path().open("a", encoding="utf-8") as handle:
            handle.write(f"{time.strftime('%Y-%m-%d %H:%M:%S')}\t{message}\n")
    except OSError:
        pass


@contextmanager
def _umask(mask: int = 0o077):
    previous = os.umask(mask)
    try:
        yield
    finally:
        os.umask(previous)


def connect(base: str, timeout: float) -> tuple[http.client.HTTPConnection, str]:
    """Open a connection to `base`; returns (connection, path prefix).

    http.client is used instead of urllib.request on purpose: urllib's header
    set gets reset by some TLS middleboxes, while http.client goes through.
    """
    parts = urlsplit(base)
    host = parts.hostname or "localhost"
    if parts.scheme == "https":
        conn: http.client.HTTPConnection = http.client.HTTPSConnection(
            host, parts.port, timeout=timeout, context=ssl.create_default_context()
        )
    else:
        conn = http.client.HTTPConnection(host, parts.port, timeout=timeout)
    return conn, parts.path.rstrip("/")


