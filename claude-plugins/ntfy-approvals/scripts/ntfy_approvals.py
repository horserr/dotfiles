def _slug(prefix: str) -> str:
    host = re.sub(r"[^a-z0-9]", "", socket.gethostname().lower())[:12] or "host"
    return f"{prefix}-{host}-{secrets.token_hex(8)}"


def load_config() -> tuple[str, str, str, str]:
    """Return (notify_topic, control_topic, base_url, token)."""
    cfg = config_path()
    notify = env("NOTIFY_TOPIC")
    control = env("CONTROL_TOPIC")

    if cfg.is_file():
        try:
            for line in cfg.read_text(encoding="utf-8", errors="replace").splitlines():
                line = line.strip()
                if line.startswith("#") or "=" not in line:
                    continue
                key, _, value = line.partition("=")
                key, value = key.strip(), value.strip()
                if key == "NOTIFY_TOPIC" and not notify:
                    notify = value
                elif key == "CONTROL_TOPIC" and not control:
                    control = value
        except OSError:
            pass

    if not (TOPIC_RE.match(notify) and TOPIC_RE.match(control)):
        notify, control = _slug("claude"), _slug("claude-ctl")
        try:
            cfg.parent.mkdir(parents=True, exist_ok=True)
            with _umask():
                cfg.write_text(
                    f"# generated by {NAME} {VERSION} — treat these as passwords\n"
                    f"NOTIFY_TOPIC={notify}\nCONTROL_TOPIC={control}\n",
                    encoding="utf-8",
                )
            cfg.chmod(0o600)
        except OSError as exc:
            log(f"could not persist topics: {exc}")
        log(f"generated topics in {cfg}")

    return (
        notify,
        control,
        env("NTFY_APPROVALS_BASE", DEFAULT_BASE).rstrip("/"),
        env("NTFY_APPROVALS_TOKEN"),
    )


# ---------------------------------------------------------------------------
# ntfy
# ---------------------------------------------------------------------------


def publish(
    message: str,
    *,
    topic: str,
    base: str,
    token: str = "",
    actions: list[dict] | None = None,
    priority: int = 3,
    title: str = "Claude Code",
    timeout: float = 8.0,
) -> bool:
    payload: dict = {
        "topic": topic,
        "title": title,
        "message": message,
        "priority": priority,
        "tags": ["bell"],
    }
    if actions:
        payload["actions"] = actions

    headers = {"Content-Type": "application/json"}
    if token:
        headers["Authorization"] = f"Bearer {token}"

    conn, _prefix = connect(base, timeout)
    try:
        conn.request(
            "POST", "/", body=json.dumps(payload).encode("utf-8"), headers=headers
        )
        response = conn.getresponse()
        response.read()
        ok = 200 <= response.status < 300
        if not ok:
            log(f"publish rejected: HTTP {response.status}")
        return ok
    except (http.client.HTTPException, OSError, ssl.SSLError, ValueError) as exc:
        log(f"publish failed: {exc}")
        return False
    finally:
        conn.close()


def publish_in_background(message: str, topic: str, priority: int = 3) -> None:
    """Detached child so the hook never waits on the network."""
    try:
        subprocess.Popen(
            [
                sys.executable,
                os.path.abspath(__file__),
                "_publish",
                topic,
                message,
                str(priority),
            ],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
    except OSError as exc:
        log(f"spawn publish failed: {exc}")


# ---------------------------------------------------------------------------
# hook input / output
# ---------------------------------------------------------------------------


def read_hook_input() -> dict:
    try:
        raw = sys.stdin.read()
    except OSError:
        return {}
    if not raw.strip():
        return {}
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        log("hook input was not valid JSON")
        return {}
    return data if isinstance(data, dict) else {}


_CONTROL_CHARS = {code: None for code in list(range(32)) + [127]}


def sanitize(text: object, limit: int = 160) -> str:
    """Strip bytes that break JSON/OSC payloads and cap the length."""
    value = str(text or "").translate(_CONTROL_CHARS).replace('"', "").replace("\\", "")
    return value[:limit]


def project_name(cwd: object) -> str:
    if not isinstance(cwd, str) or not cwd:
        return "claude"
    name = re.split(r"[\\/]", cwd.rstrip("/\\"))[-1]
    return name or "claude"


def sequence(title: str, body: str) -> str:
    """BEL + OSC 0/9/777/99 — Claude Code writes these to its own terminal."""
    return (
        "\a"
        f"\x1b]0;{title}: {body}\a"
        f"\x1b]9;{body}\a"
        f"\x1b]777;notify;{title};{body}\a"
        f"\x1b]99;i=claude:d=1;{title}: {body}\a"
    )


def emit(payload: dict) -> None:
    """Exactly one JSON object per hook run — anything else is dropped."""
    sys.stdout.write(json.dumps(payload) + "\n")
    sys.stdout.flush()


def frame(title: str, body: str, extra: dict | None = None) -> dict:
    payload = {"terminalSequence": sequence(title, body)}
    if extra:
        payload.update(extra)
    return payload


def run(argv: list[str]) -> str:
    try:
        completed = subprocess.run(argv, capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return ""
    return completed.stdout.strip()


def tmux_hint(text: str) -> None:
    if not env("TMUX"):
        return
    run(["tmux", "display-message", "-d", "8000", text])


