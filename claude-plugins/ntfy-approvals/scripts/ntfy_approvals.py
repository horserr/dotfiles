def inject_text(text: str) -> None:
    target = env("NTFY_APPROVALS_TMUX_TARGET")
    if not target and env("TMUX"):
        target = run(
            [
                "tmux",
                "display-message",
                "-p",
                "#{session_name}:#{window_index}.#{pane_index}",
            ]
        )
    if not target:
        log("tmux: no target, dropping text")
        return
    run(["tmux", "send-keys", "-t", target, "-l", "--", text])
    run(["tmux", "send-keys", "-t", target, "Enter"])
    log(f"tmux: injected into {target}")


def handle_event(raw: str, last_id: str) -> str:
    """Process one SSE data payload; returns the newest message id seen."""
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        return last_id
    if not isinstance(data, dict) or data.get("event") != "message":
        return last_id

    message_id = data.get("id") or last_id
    message = str(data.get("message") or "").strip()
    if not message:
        return message_id

    if message.startswith(("allow ", "deny ")):
        action, _, request_id = message.partition(" ")
        request_id = request_id.strip()
        if not REQ_RE.match(request_id):
            log(f"relay: bad request id {request_id!r}")
            return message_id
        directory = control_dir()
        try:
            directory.mkdir(parents=True, exist_ok=True)
            with _umask():
                (directory / f"{request_id}.json").write_text(
                    json.dumps({"action": action}) + "\n", encoding="utf-8"
                )
            log(f"relay: {action} -> {request_id}")
        except OSError as exc:
            log(f"relay: write failed: {exc}")
    elif flag("NTFY_APPROVALS_TMUX", False):
        inject_text(message)
    else:
        log(f"relay: ignored text (NTFY_APPROVALS_TMUX=0): {message}")
    return message_id


def cmd_listen() -> int:
    _notify, control_topic, base, token = load_config()
    headers = {"Accept": "text/event-stream"}
    if token:
        headers["Authorization"] = f"Bearer {token}"

    print(f"relay: {base}/{control_topic} (ctrl-c to stop)", flush=True)
    since = str(int(time.time()))
    last_id = ""

    while True:
        path = f"/{control_topic}/sse?since={last_id or since}"
        conn = None
        try:
            conn, _prefix = connect(base, timeout=3600)
            conn.request("GET", path, headers=headers)
            response = conn.getresponse()
            if response.status != 200:
                log(f"relay: HTTP {response.status}, retrying")
            else:
                while True:
                    raw_line = response.readline()
                    if not raw_line:
                        break
                    line = raw_line.decode("utf-8", "replace").rstrip("\r\n")
                    if line.startswith("data:"):
                        last_id = handle_event(line[5:].strip(), last_id)
        except KeyboardInterrupt:
            print()
            return 0
        except (http.client.HTTPException, OSError, ssl.SSLError) as exc:
            log(f"relay: reconnecting after {exc}")
        finally:
            if conn is not None:
                conn.close()
        try:
            time.sleep(3)
        except KeyboardInterrupt:
            print()
            return 0


