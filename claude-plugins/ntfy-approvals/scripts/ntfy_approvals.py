def cmd_notify() -> int:
    payload = read_hook_input()
    event = payload.get("hook_event_name", "")
    ntype = payload.get("notification_type", "")
    project = project_name(payload.get("cwd"))

    if event == "Notification":
        if ntype == "permission_prompt":
            body = (
                payload.get("message")
                or f"still waiting for approval: {payload.get('tool_name', 'tool')}"
            )
        elif ntype == "idle_prompt":
            body = "finished, waiting for you"
        elif ntype in ("elicitation_dialog", "elicitation_url_dialog"):
            body = "MCP server needs your input"
        elif ntype == "agent_needs_input":
            body = "background agent needs your input"
        elif ntype == "agent_completed":
            body = "background agent finished"
        else:
            return 0
    elif event == "Stop":
        if not flag("NTFY_APPROVALS_ON_DONE", False):
            return 0
        body = "turn finished"
    elif event == "StopFailure":
        body = f"API error: {payload.get('error', 'unknown')}"
    else:
        return 0

    title = "Claude Code"
    text = sanitize(f"{project}: {body}")
    log(f"notify event={event} type={ntype} body={text}")

    if flag("NTFY_APPROVALS_PUSH", True):
        notify_topic, _control, _base, _token = load_config()
        publish_in_background(text, notify_topic)

    tmux_hint(f"Claude Code: {text}")
    emit(frame(title, text))
    return 0


