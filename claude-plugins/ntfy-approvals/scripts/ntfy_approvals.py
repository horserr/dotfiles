def cmd_topic() -> int:
    notify_topic, control_topic, base, _token = load_config()
    host = re.sub(r"^[a-z]+://", "", base)
    link = f"ntfy://{host}/{notify_topic}"
    print(f"notify  : {base}/{notify_topic}")
    print(f"control : {base}/{control_topic}")
    print(f"phone   : {link}")
    if flag("NTFY_APPROVALS_QR", True):
        try:
            color = flag("NTFY_APPROVALS_QR_COLOR", sys.stdout.isatty())
            print()
            print(qrgen.as_text(link, color=color))
        except ValueError as exc:  # payload longer than version 10
            print(f"(QR skipped: {exc})")
    return 0


def _which(program: str) -> str | None:
    from shutil import which

    return which(program)


def cmd_status() -> int:
    notify_topic, control_topic, base, _token = load_config()
    relay = "running" if _relay_running() else "stopped"
    pending = len(list(control_dir().glob("*.json"))) if control_dir().is_dir() else 0
    print(f"state   : {state_dir()}")
    print(f"notify  : {notify_topic}")
    print(f"control : {control_topic}")
    print(f"base    : {base}")
    print(f"relay   : {relay}")
    print(f"pending : {pending} decision file(s)")
    return 0


def _relay_running() -> bool:
    if _which("pgrep"):
        try:
            completed = subprocess.run(
                ["pgrep", "-f", "ntfy_approvals.py control listen"],
                capture_output=True,
                text=True,
                timeout=5,
            )
            return completed.returncode == 0
        except (OSError, subprocess.SubprocessError):
            return False
    return False


def cmd_send(argv: list[str]) -> int:
    if not argv:
        print(f"usage: {Path(__file__).name} control send <text>", file=sys.stderr)
        return 2
    _notify, control_topic, base, token = load_config()
    if not publish(" ".join(argv), topic=control_topic, base=base, token=token):
        print("publish failed", file=sys.stderr)
        return 1
    print(f"sent to {base}/{control_topic}")
    return 0


def cmd_publish_child(argv: list[str]) -> int:
    if len(argv) < 2:
        return 2
    topic, message = argv[0], argv[1]
    priority = int(argv[2]) if len(argv) > 2 and argv[2].isdigit() else 3
    publish(
        message,
        topic=topic,
        base=env("NTFY_APPROVALS_BASE", DEFAULT_BASE).rstrip("/"),
        token=env("NTFY_APPROVALS_TOKEN"),
        priority=priority,
    )
    return 0


