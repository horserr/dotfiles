def wait_for_decision(request_id: str, timeout_s: float) -> str | None:
    directory = control_dir()
    path = directory / f"{request_id}.json"
    deadline = time.monotonic() + timeout_s
    try:
        while time.monotonic() < deadline:
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
                action = str(data.get("action", "")).strip().lower()
                if action in ("allow", "deny"):
                    return action
            except (OSError, json.JSONDecodeError):
                pass
            time.sleep(0.5)
        return None
    finally:
        try:
            path.unlink()
        except OSError:
            pass


def cmd_approve() -> int:
    payload = read_hook_input()
    tool = payload.get("tool_name") or "tool"
    tool_input = payload.get("tool_input") or {}
    detail = ""
    if isinstance(tool_input, dict):
        detail = tool_input.get("command") or tool_input.get("file_path") or ""

    project = project_name(payload.get("cwd"))
    title = "Claude Code"
    body = sanitize(f"{project}: needs approval: {tool}")
    tmux_hint(f"Claude Code: {body}")

    timeout_s = number("NTFY_APPROVALS_APPROVE_TIMEOUT", 120)
    if not flag("NTFY_APPROVALS_APPROVE", True) or timeout_s <= 0:
        emit(frame(title, body))
        return 0

    notify_topic, control_topic, base, token = load_config()
    request_id = f"{int(time.time())}-{secrets.token_hex(4)}"
    control_url = f"{base}/{control_topic}"

    action_headers = {"Authorization": f"Bearer {token}"} if token else {}
    actions = [
        {
            "action": "http",
            "label": "✅ Allow",
            "url": control_url,
            "method": "POST",
            "body": f"allow {request_id}",
            "clear": True,
            **({"headers": action_headers} if action_headers else {}),
        },
        {
            "action": "http",
            "label": "⛔ Deny",
            "url": control_url,
            "method": "POST",
            "body": f"deny {request_id}",
            "clear": True,
            **({"headers": action_headers} if action_headers else {}),
        },
    ]

    message = f"{project}: needs approval · {tool}"
    if detail:
        message = f"{message} · {sanitize(detail)}"
    message = sanitize(message)

    log(f"approve req={request_id} tool={tool}")

    if not publish(
        message, topic=notify_topic, base=base, token=token, actions=actions, priority=5
    ):
        log(f"approve: publish failed, not waiting (req={request_id})")
        emit(frame(title, body))
        return 0

    decision = wait_for_decision(request_id, timeout_s)
    log(f"approve req={request_id} decision={decision or 'timeout'}")

    if decision == "allow":
        emit(
            frame(
                title,
                body,
                {
                    "hookSpecificOutput": {
                        "hookEventName": "PermissionRequest",
                        "decision": {"behavior": "allow"},
                    }
                },
            )
        )
    elif decision == "deny":
        emit(
            frame(
                title,
                body,
                {
                    "hookSpecificOutput": {
                        "hookEventName": "PermissionRequest",
                        "decision": {
                            "behavior": "deny",
                            "message": "Denied from phone",
                        },
                    }
                },
            )
        )
    else:
        emit(frame(title, body))
    return 0


