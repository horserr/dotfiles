#!/usr/bin/env bash
# claude-remote — shared helpers for the hook scripts.
# Deliberately jq-free: works on a bare remote server with bash + curl only.

CR_NAME="claude-remote"
CR_VERSION="0.1.0"

# ---------------------------------------------------------------------------
# state
# ---------------------------------------------------------------------------
cr_state_dir() {
  printf '%s' "${CLAUDE_REMOTE_STATE_DIR:-$HOME/.claude}"
}

cr_config_file() {
  printf '%s/claude-remote.env' "$(cr_state_dir)"
}

cr_control_dir() {
  printf '%s/control' "$(cr_state_dir)"
}

# cr_log <text> — only when CLAUDE_REMOTE_DEBUG=1
cr_log() {
  [ "${CLAUDE_REMOTE_DEBUG:-0}" = "1" ] || return 0
  printf '%s\t%s\n' "$(date '+%F %T')" "$*" \
    >>"$(cr_state_dir)/claude-remote.log" 2>/dev/null || true
}

# ---------------------------------------------------------------------------
# tiny JSON helpers (hook payloads are single-line JSON)
# ---------------------------------------------------------------------------

# jget <json> <key> -> first string value of "key"
jget() {
  printf '%s' "$1" \
    | tr -d '\r\n' \
    | sed -n 's/.*"'"$2"'"[[:space:]]*:[[:space:]]*"\([^"\\]*\)".*/\1/p' \
    | head -n 1
}

# json_escape <text> -> safe to embed inside a JSON string
json_escape() {
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

# cr_sanitize <text> -> strips bytes that break JSON / OSC payloads, caps length
cr_sanitize() {
  local s
  s=$(printf '%s' "$1" | LC_ALL=C tr -d '[:cntrl:]"\\')
  printf '%s' "${s:0:160}"
}

# cr_project <cwd> -> last path segment, / and \ aware
cr_project() {
  local name
  name=$(printf '%s' "$1" | sed 's#/*$##; s#.*[\\/]##')
  printf '%s' "${name:-claude}"
}

# ---------------------------------------------------------------------------
# topics
# ---------------------------------------------------------------------------
cr_rand_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1" 2>/dev/null && return 0
  fi
  od -An -tx1 -N "$1" /dev/urandom 2>/dev/null | tr -d ' \n'
}

cr_topic_slug() {
  local prefix=$1 host rand
  host=$(hostname 2>/dev/null | tr 'A-Z' 'a-z' | tr -cd 'a-z0-9' | cut -c1-12)
  [ -n "$host" ] || host="host"
  rand=$(cr_rand_hex 8)
  [ -n "$rand" ] || rand=$(date +%s | cut -c1-10)
  printf '%s-%s-%s' "$prefix" "$host" "$rand"
}

cr_valid_topic() {
  case "$1" in
    ''|*[!A-Za-z0-9_-]*) return 1 ;;
    *) [ "${#1}" -le 64 ] ;;
  esac
}

# cr_load_config — sets NOTIFY_TOPIC / CONTROL_TOPIC / NTFY_BASE / NTFY_TOKEN.
# Generates and persists a random topic pair on first use (0600).
cr_load_config() {
  local dir file
  dir=$(cr_state_dir)
  file=$(cr_config_file)
  mkdir -p "$dir" 2>/dev/null || true
  chmod 700 "$dir" 2>/dev/null || true

  if [ -f "$file" ]; then
    [ -n "${NOTIFY_TOPIC:-}" ]  || NOTIFY_TOPIC=$(sed -n 's/^NOTIFY_TOPIC=//p' "$file" | head -n 1)
    [ -n "${CONTROL_TOPIC:-}" ] || CONTROL_TOPIC=$(sed -n 's/^CONTROL_TOPIC=//p' "$file" | head -n 1)
  fi

  if ! cr_valid_topic "${NOTIFY_TOPIC:-}" || ! cr_valid_topic "${CONTROL_TOPIC:-}"; then
    NOTIFY_TOPIC=$(cr_topic_slug claude)
    CONTROL_TOPIC=$(cr_topic_slug claude-ctl)
    ( umask 077
      printf '# generated by %s %s — treat as passwords\nNOTIFY_TOPIC=%s\nCONTROL_TOPIC=%s\n' \
        "$CR_NAME" "$CR_VERSION" "$NOTIFY_TOPIC" "$CONTROL_TOPIC" >"$file" )
    chmod 600 "$file" 2>/dev/null || true
    cr_log "generated topics in $file"
  fi

  NTFY_BASE=${CLAUDE_NOTIFY_NTFY_BASE:-https://ntfy.sh}
  NTFY_BASE=${NTFY_BASE%/}
  NTFY_TOKEN=${CLAUDE_NOTIFY_TOKEN:-}
  export NOTIFY_TOPIC CONTROL_TOPIC NTFY_BASE NTFY_TOKEN
}

# ---------------------------------------------------------------------------
# ntfy
# ---------------------------------------------------------------------------

# cr_publish <topic> <message> [actions-json] [priority]
cr_publish() {
  local topic=$1 msg=$2 actions=${3:-} prio=${4:-3}
  local payload hdr=()
  command -v curl >/dev/null 2>&1 || return 1
  if [ -n "${NTFY_TOKEN:-}" ]; then
    hdr=(-H "Authorization: Bearer $NTFY_TOKEN")
  fi
  if [ -n "$actions" ]; then
    payload=$(printf '{"topic":"%s","title":"Claude Code","message":"%s","priority":%s,"tags":["bell"],"actions":%s}' \
      "$topic" "$(json_escape "$msg")" "$prio" "$actions")
  else
    payload=$(printf '{"topic":"%s","title":"Claude Code","message":"%s","priority":%s,"tags":["bell"]}' \
      "$topic" "$(json_escape "$msg")" "$prio")
  fi
  curl -fsS -m 8 -H "Content-Type: application/json" ${hdr[@]+"${hdr[@]}"} \
    -d "$payload" "$NTFY_BASE/" >/dev/null 2>&1
}

# ---------------------------------------------------------------------------
# terminal
# ---------------------------------------------------------------------------

# cr_seq_json <title> <already-sanitized body> -> JSON-escaped escape sequence
# (no surrounding quotes, so callers can build ONE object per hook run)
cr_seq_json() {
  printf '\\u0007\\u001b]0;%s\\u0007\\u001b]9;%s\\u0007\\u001b]777;notify;%s;%s\\u0007\\u001b]99;i=claude:d=1;%s\\u0007' \
    "$1: $2" "$2" "$1" "$2" "$1: $2"
}

# cr_frame <title> <body> [extra json fields] -> one complete hook JSON object
cr_frame() {
  printf '{"terminalSequence":"%s"%s}\n' "$(cr_seq_json "$1" "$2")" "${3:-}"
}

# cr_tmux_hint <text> — status-line fallback when the terminal drops OSC
cr_tmux_hint() {
  [ -n "${TMUX:-}" ] || return 0
  command -v tmux >/dev/null 2>&1 || return 0
  tmux display-message -d 8000 "$1" >/dev/null 2>&1 || true
}
